const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const { readCatalog } = require("../lib/catalog.cjs");
const { verifyEnvelope } = require("../lib/envelope.cjs");
const { validateManifest } = require("../lib/schema.cjs");
const { createPublication } = require("../lib/publication.cjs");
const trusted = require("../trusted-keys.json");

const directory = process.env.PUBLICATION_DIR;
if (!directory || !process.env.REGISTRY_SIGNING_KEY)
  throw new Error("Publication directory and signing key required");
const git = (args, cwd = process.cwd()) =>
  execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();
const sourceCommit = git(["rev-parse", "HEAD"]);
const latestMain = () =>
  git(["ls-remote", "origin", "refs/heads/main"]).split(/\s/)[0];
if (sourceCommit !== latestMain()) {
  console.log(
    "Skipped stale source; the newer main workflow owns publication.",
  );
  process.exit(0);
}
const manifestPath = path.join(directory, "manifest.json");
const previous = fs.existsSync(manifestPath)
  ? validateManifest(verifyEnvelope(fs.readFileSync(manifestPath), trusted))
  : undefined;
const envelope = createPublication({
  data: readCatalog(),
  previous,
  sourceCommit,
  headCommit: latestMain(),
  keyId: "primary-2026-10",
  privateKey: process.env.REGISTRY_SIGNING_KEY,
});
if (!envelope) {
  console.log("This source is already published.");
  process.exit(0);
}
const manifest = validateManifest(
  verifyEnvelope(JSON.stringify(envelope), trusted),
);
const version = manifest.manifestVersion;
const history = path.join(directory, "history", `${version}.json`);
if (fs.existsSync(history))
  throw new Error("Refusing to overwrite a published version");
fs.mkdirSync(path.dirname(history), { recursive: true });
const bytes = JSON.stringify(envelope) + "\n";
fs.writeFileSync(manifestPath, bytes);
fs.writeFileSync(history, bytes);
// These files let desktop vendor the exact validated source without trusting a
// later mutable branch. Their digests are captured in desktop provenance.
fs.copyFileSync("lib/schema.cjs", path.join(directory, "schema.cjs"));
fs.copyFileSync("lib/envelope.cjs", path.join(directory, "envelope.cjs"));
fs.copyFileSync(
  "lib/registrySelection.js",
  path.join(directory, "registrySelection.js"),
);
fs.copyFileSync("trusted-keys.json", path.join(directory, "trusted-keys.json"));
fs.writeFileSync(
  path.join(directory, "README.md"),
  `# Published model registry\n\nVersion ${version}, source [${sourceCommit}](https://github.com/OpenWhispr/model-registry/commit/${sourceCommit}). Generated by the protected main publication workflow.\n`,
);
git(["config", "user.name", "github-actions[bot]"], directory);
git(
  [
    "config",
    "user.email",
    "41898282+github-actions[bot]@users.noreply.github.com",
  ],
  directory,
);
git(
  [
    "add",
    "manifest.json",
    "history",
    "schema.cjs",
    "envelope.cjs",
    "registrySelection.js",
    "trusted-keys.json",
    "README.md",
  ],
  directory,
);
git(
  ["commit", "-m", `Publish catalog ${version} from ${sourceCommit}`],
  directory,
);
if (sourceCommit !== latestMain()) {
  console.log("Skipped stale source before push.");
  process.exit(0);
}
git(["push", "origin", "HEAD:published"], directory);
console.log(`Published verified catalog ${version} from ${sourceCommit}`);
